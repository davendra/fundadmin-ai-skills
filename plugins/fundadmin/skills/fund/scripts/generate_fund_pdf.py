def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a fund review PDF from JSON or markdown review input."
    )
    parser.add_argument("input_path", nargs="?", help="Input JSON or markdown file")
    parser.add_argument("output_path", nargs="?", help="Optional output PDF path")
    parser.add_argument("--input", dest="input_flag", help="Input JSON or markdown file")
    parser.add_argument("--output", dest="output_flag", help="Output PDF path")
    args = parser.parse_args(argv)

    if args.input_flag and args.input_path:
        parser.error("provide input either positionally or with --input, not both")
    if args.output_flag and args.output_path:
        parser.error("provide output either positionally or with --output, not both")

    args.input_resolved = args.input_flag or args.input_path
    args.output_resolved = args.output_flag or args.output_path or "FUND-REVIEW-REPORT.pdf"

    if not args.input_resolved:
        parser.error("an input file is required")

    return args


def read_input_data(input_path: Path) -> dict:
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    raw = input_path.read_text(encoding="utf-8")
    if not raw.strip():
        raise ValueError("Input report is empty")
    stripped = raw.lstrip()

    if input_path.suffix.lower() == ".json" or stripped.startswith("{"):
        def unique_object(pairs):
            result = {}
            for key, value in pairs:
                if key in result:
                    raise ValueError(f"Invalid JSON input: duplicate key {key!r}")
                result[key] = value
            return result

        try:
            data = json.loads(raw, object_pairs_hook=unique_object)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Invalid JSON input: {exc.msg} (line {exc.lineno}, column {exc.colno})") from exc
        if not isinstance(data, dict):
            raise ValueError("JSON input must contain a top-level object")
        return normalize_report_data(data)

    report = normalize_report_data({"source_markdown": raw})
    report.markdown = raw
    return report


class NormalizedReport(dict):
    """Internal provenance is kept outside user-supplied JSON fields."""
    markdown = None


def validate_report_data(data: dict) -> None:
    """Reject malformed structured reports before creating an output file."""
    if not isinstance(data, dict) or not data:
        raise ValueError("Report must be a non-empty JSON object")

    def finite(value, path):
        if isinstance(value, float) and not math.isfinite(value):
            raise ValueError(f"{path} must be finite")
        if isinstance(value, dict):
            for key, child in value.items():
                finite(child, f"{path}.{key}")
        elif isinstance(value, list):
            for index, child in enumerate(value):
                finite(child, f"{path}[{index}]")

    finite(data, "report")
    for key in ("details", "risks", "risk_counts"):
        if key in data and not isinstance(data[key], dict):
            raise ValueError(f"{key} must be an object")
    for key in ("provisions", "clauses", "compliance_flags", "obligations",
                "negotiation_priorities", "next_steps", "missing_protections"):
        if key not in data:
            continue
        if not isinstance(data[key], list):
            raise ValueError(f"{key} must be an array")
        for item in data[key]:
            expected = (dict,) if key in ("provisions", "clauses", "obligations") else (str, dict)
            if not isinstance(item, expected):
                raise ValueError(f"{key} contains an invalid item")
    for key in ("risks", "risk_counts"):
        for level in ("high", "medium", "low"):
            value = data.get(key, {}).get(level, 0)
            if isinstance(value, bool) or not isinstance(value, int) or value < 0:
                raise ValueError(f"{key}.{level} must be a non-negative integer")
    score = data.get("score")
    scale = data.get("score_scale", 100)
    if isinstance(scale, bool) or not isinstance(scale, (int, float)) or scale <= 0:
        raise ValueError("score_scale must be a positive number")
    if score is not None and (isinstance(score, bool) or
                              not isinstance(score, (int, float)) or not 0 <= score <= scale):
        raise ValueError("score must be a number between zero and score_scale, or null")
    for key in ("score_label", "grade", "grade_label", "executive_summary", "source_markdown"):
        if key in data and data[key] is not None and not isinstance(data[key], str):
            raise ValueError(f"{key} must be text")
    if "score_label" in data and not str(data["score_label"] or "").strip():
        raise ValueError("score_label must be non-empty text")


def normalize_report_data(data: dict) -> dict:
    if isinstance(data, NormalizedReport):
        return data
    validate_report_data(data)
    details = dict(data.get("details") or {})
    details.setdefault("fund_name", data.get("fund_name", "N/A"))
    details.setdefault("fund_type", data.get("fund_type", "N/A"))
    details.setdefault("vintage", data.get("vintage", "N/A"))
    details.setdefault("aum", data.get("aum", data.get("fund_size", "N/A")))
    details.setdefault("gp_entity", data.get("gp_entity", "N/A"))
    details.setdefault("management_fee", data.get("management_fee", "N/A"))
    details.setdefault("carry", data.get("carry", data.get("carried_interest", "N/A")))
    details.setdefault("hurdle_rate", data.get("hurdle_rate", data.get("preferred_return", "N/A")))
    details.setdefault("fund_term", data.get("fund_term", "N/A"))
    details.setdefault("governing_law", data.get("governing_law", "N/A"))

    # Support both "provisions" and "clauses" as source keys
    provisions = list(data.get("provisions") or data.get("clauses") or [])
    risk_counts = dict(data.get("risks") or data.get("risk_counts") or {})
    if not risk_counts:
        risk_counts = {"high": 0, "medium": 0, "low": 0}
        for provision in provisions:
            risk = str(provision.get("risk", "low")).lower()
            if risk not in risk_counts:
                continue
            risk_counts[risk] += 1

    # Map high_clauses -> high_provisions etc. for compatibility
    for level in ("high", "medium", "low"):
        clauses_key = f"{level}_clauses"
        provisions_key = f"{level}_provisions"
        if clauses_key in risk_counts and provisions_key not in risk_counts:
            risk_counts[provisions_key] = risk_counts[clauses_key]

    grade = str(data.get("grade", "N/A"))
    grade_label = data.get("grade_label") or GRADE_LABELS.get(grade, "")

    # Build compliance_flags from explicit data or from missing_protections
    compliance_flags = list(data.get("compliance_flags") or [])
    if not compliance_flags and data.get("missing_protections"):
        for item in data["missing_protections"]:
            compliance_flags.append({"status": "FAIL", "regulation": "", "detail": item})

    report = NormalizedReport({
        "score": data.get("score"),
        "score_label": data.get("score_label", DEFAULT_SCORE_LABEL),
        "score_scale": data.get("score_scale", 100),
        "source_markdown": data.get("source_markdown"),
        "grade": grade,
        "grade_label": grade_label,
        "details": details,
        "executive_summary": data.get("executive_summary", "No summary available."),
        "risks": {
            "high": int(risk_counts.get("high", 0) or 0),
            "medium": int(risk_counts.get("medium", 0) or 0),
            "low": int(risk_counts.get("low", 0) or 0),
            "high_provisions": risk_counts.get("high_provisions", "None"),
            "medium_provisions": risk_counts.get("medium_provisions", "None"),
            "low_provisions": risk_counts.get("low_provisions", "None"),
        },
        "provisions": provisions,
        "compliance_flags": compliance_flags,
        "obligations": list(data.get("obligations") or []),
        "negotiation_priorities": list(data.get("negotiation_priorities") or []),
        "next_steps": list(data.get("next_steps") or []),
    })
    report.source = data
    return report


def parse_markdown_report(markdown: str) -> dict:
    lines = markdown.splitlines()
    details = extract_details_table(lines)
    provisions = extract_provisions(lines)
    risks = summarize_provision_risks(provisions)

    compliance_lines = extract_section_list(markdown, "Compliance Flags")
    next_steps = extract_section_list(markdown, "Recommended Next Steps")
    if not next_steps:
        next_steps = extract_section_list(markdown, "Next Steps")
    negotiation_priorities = extract_section_list(markdown, "Negotiation Priorities")

    return {
        "source_markdown": markdown,
        "score": extract_score(markdown),
        "grade": extract_grade(markdown),
        "grade_label": extract_grade_label(markdown),
        "details": details,
        "executive_summary": extract_section_body(markdown, "Executive Summary") or "No summary available.",
        "risks": risks,
        "provisions": provisions,
        "compliance_flags": [
            {"status": "WARNING", "regulation": "", "detail": line} for line in compliance_lines
        ],
        "obligations": extract_obligations(markdown),
        "negotiation_priorities": negotiation_priorities,
        "next_steps": next_steps,
    }


def extract_score(markdown: str):
    patterns = [
        r"(?:LPA Safety Score|Completeness Score|Safety Score|Compliance Score):\s*(\d+)\s*/\s*100",
        r"##\s+LPA Safety Score:\s*(\d+)\s*/\s*100",
    ]
    for pattern in patterns:
        match = re.search(pattern, markdown, re.IGNORECASE)
        if match:
            return int(match.group(1))
    return None


def extract_grade(markdown: str) -> str:
    match = re.search(r"Grade:\s*([A-F][+]?)", markdown)
    return match.group(1) if match else "N/A"


def extract_grade_label(markdown: str) -> str:
    match = re.search(r"Grade:\s*[A-F][+]?\s*(?:[-—]\s*|\()([^)\\n]+)", markdown)
    if match:
        return match.group(1).strip(" )")
    grade = extract_grade(markdown)
    return GRADE_LABELS.get(grade, "")


def extract_section_body(markdown: str, heading: str) -> str:
    pattern = re.compile(
        rf"^##\s+{re.escape(heading)}\s*$\n(?P<body>.*?)(?=^##\s+|\Z)",
        re.MULTILINE | re.DOTALL,
    )
    match = pattern.search(markdown)
    if not match:
        return ""
    body = match.group("body").strip()
    return re.sub(r"\n{2,}", "\n\n", body)


def extract_section_list(markdown: str, heading: str) -> list[str]:
    body = extract_section_body(markdown, heading)
    items: list[str] = []
    for line in body.splitlines():
        match = re.match(r"^\s*(?:[-*]|\d+\.)\s+(.*)$", line)
        if match:
            items.append(match.group(1).strip())
    return items


def extract_details_table(lines: list[str]) -> dict:
    mapping = {
        "fund name": "fund_name",
        "fund type": "fund_type",
        "gp entity": "gp_entity",
        "general partner": "gp_entity",
        "vintage": "vintage",
        "aum / fund size": "aum",
        "aum": "aum",
        "fund size": "aum",
        "management fee": "management_fee",
        "carried interest": "carry",
        "carry": "carry",
        "preferred return / hurdle": "hurdle_rate",
        "preferred return": "hurdle_rate",
        "hurdle rate": "hurdle_rate",
        "fund term": "fund_term",
        "governing law": "governing_law",
    }
    details: dict[str, str] = {}
    for line in lines:
        match = re.match(r"^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|$", line)
        if not match:
            continue
        key, value = match.groups()
        normalized_key = key.strip().lower()
        if normalized_key in {"field", "value", "---", "-------"}:
            continue
        if set(normalized_key) == {"-"}:
            continue
        mapped = mapping.get(normalized_key)
        if mapped:
            details[mapped] = value.strip()
    return details


def extract_provisions(lines: list[str]) -> list[dict]:
    provisions: list[dict] = []
    current_risk = "low"
    current: dict | None = None

    for line in lines:
        risk_heading = re.match(r"^###\s+(HIGH|MEDIUM|LOW)\s+RISK", line)
        if risk_heading:
            current_risk = risk_heading.group(1).lower()
            continue

        provision_heading = re.match(r"^####\s+(.+?)\s+[—-]\s+Section\s+(.+)$", line)
        if provision_heading:
            if current:
                provisions.append(current)
            current = {
                "name": provision_heading.group(1).strip(),
                "section": provision_heading.group(2).strip(),
                "risk": current_risk,
            }
            continue

        if current is None:
            continue

        bullet = re.match(r"^- \*\*(.+?)\*\*:\s+(.*)$", line)
        if not bullet:
            continue
        label, value = bullet.groups()
        normalized = label.strip().lower()
        if normalized == "what it says":
            current["summary"] = value.strip()
        elif normalized in {"why it is risky", "why it matters"}:
            current["risk_explanation"] = value.strip()
        elif normalized == "market standard":
            current["market_standard"] = value.strip()
        elif normalized == "recommended change":
            current["recommendation"] = value.strip()

    if current:
        provisions.append(current)

    return provisions


def summarize_provision_risks(provisions: list[dict]) -> dict:
    counts = {"high": 0, "medium": 0, "low": 0}
    names = {"high": [], "medium": [], "low": []}

    for provision in provisions:
        risk = str(provision.get("risk", "low")).lower()
        if risk not in counts:
            continue
        counts[risk] += 1
        names[risk].append(provision.get("name", "Unnamed Provision"))

    return {
        "high": counts["high"],
        "medium": counts["medium"],
        "low": counts["low"],
        "high_provisions": ", ".join(names["high"]) or "None",
        "medium_provisions": ", ".join(names["medium"]) or "None",
        "low_provisions": ", ".join(names["low"]) or "None",
    }


def extract_obligations(markdown: str) -> list[dict]:
    body = extract_section_body(markdown, "Obligations & Deadlines") or extract_section_body(
        markdown, "Obligations Timeline"
    )
    if not body:
        return []

    obligations: list[dict] = []
    for line in body.splitlines():
        match = re.match(r"^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|?$", line)
        if not match:
            continue
        cells = [cell.strip() for cell in match.groups()]
        if cells[0].lower() in {"obligation", "------------"}:
            continue
        obligations.append(
            {
                "description": cells[0],
                "type": cells[1],
                "trigger": cells[2],
                "deadline": cells[3],
            }
        )
    return obligations


