def create_score_gauge(score: int, size: int = 280):
    """Large score gauge for the cover page."""
    ensure_reportlab()
    d = Drawing(size, size * 0.65)
    cx, cy = size / 2, size * 0.55
    radius = size * 0.4

    segments = [
        (0, 36, COLORS["danger"]),
        (36, 72, HexColor("#ed8936")),
        (72, 108, COLORS["warning"]),
        (108, 144, HexColor("#68d391")),
        (144, 180, COLORS["success"]),
    ]

    for start, end, color in segments:
        d.add(Wedge(cx, cy, radius, 180 + start, 180 + end, fillColor=color, strokeColor=white, strokeWidth=2))

    d.add(Circle(cx, cy, radius * 0.65, fillColor=white, strokeColor=None))
    d.add(String(cx, cy - 8, str(int(score)), fontSize=48, fillColor=COLORS["primary"], textAnchor="middle", fontName="Helvetica-Bold"))
    d.add(String(cx, cy - 30, "/ 100", fontSize=14, fillColor=COLORS["gray_text"], textAnchor="middle", fontName="Helvetica"))

    angle_deg = 180 + (score / 100) * 180
    angle_rad = math.radians(angle_deg)
    needle_len = radius * 0.55
    nx = cx + needle_len * math.cos(angle_rad)
    ny = cy + needle_len * math.sin(angle_rad)
    d.add(Line(cx, cy, nx, ny, strokeColor=COLORS["primary"], strokeWidth=3))
    d.add(Circle(cx, cy, 6, fillColor=COLORS["primary"], strokeColor=None))

    return d


def create_grade_badge(grade: str, size: int = 60):
    """Colored grade badge circle."""
    ensure_reportlab()
    d = Drawing(size, size)
    cx, cy = size / 2, size / 2

    if grade in ("F", "D"):
        bg = COLORS["danger"]
    elif grade == "C":
        bg = COLORS["warning"]
    else:
        bg = COLORS["success"]

    d.add(Circle(cx, cy, size * 0.45, fillColor=bg, strokeColor=None))
    d.add(String(cx, cy - 10, grade, fontSize=28, fillColor=white, textAnchor="middle", fontName="Helvetica-Bold"))

    return d


def create_risk_bar_chart(high: int, medium: int, low: int, width: int = 460, height: int = 60):
    """Horizontal stacked bar chart for risk breakdown."""
    ensure_reportlab()
    d = Drawing(width, height)
    total = high + medium + low
    if total == 0:
        return d

    bar_width = width * 0.85
    bar_height = 28
    x_start = width * 0.075
    y = height * 0.45

    high_w = (high / total) * bar_width
    med_w = (medium / total) * bar_width
    low_w = (low / total) * bar_width

    # Rounded-corner effect via overlapping rects
    if high_w > 0:
        d.add(Rect(x_start, y, high_w, bar_height, fillColor=COLORS["danger"], strokeColor=None))
        if high_w > 20:
            d.add(String(x_start + high_w / 2, y + 8, str(high), fontSize=11, fillColor=white, textAnchor="middle", fontName="Helvetica-Bold"))
    if med_w > 0:
        d.add(Rect(x_start + high_w, y, med_w, bar_height, fillColor=COLORS["warning"], strokeColor=None))
        if med_w > 20:
            d.add(String(x_start + high_w + med_w / 2, y + 8, str(medium), fontSize=11, fillColor=white, textAnchor="middle", fontName="Helvetica-Bold"))
    if low_w > 0:
        d.add(Rect(x_start + high_w + med_w, y, low_w, bar_height, fillColor=COLORS["success"], strokeColor=None))
        if low_w > 20:
            d.add(String(x_start + high_w + med_w + low_w / 2, y + 8, str(low), fontSize=11, fillColor=white, textAnchor="middle", fontName="Helvetica-Bold"))

    # Legend below bar
    legend_y = y - 18
    legend_items = [
        ("High Risk", COLORS["danger"]),
        ("Medium Risk", COLORS["warning"]),
        ("Low Risk", COLORS["success"]),
    ]
    lx = x_start
    for label_text, color in legend_items:
        d.add(Rect(lx, legend_y, 10, 10, fillColor=color, strokeColor=None))
        d.add(String(lx + 14, legend_y, label_text, fontSize=9, fillColor=COLORS["dark_text"], fontName="Helvetica"))
        lx += 100

    return d


def create_metric_box(label: str, value: str, color, box_width: float = 120, box_height: float = 60):
    """Small metric card for the executive summary grid."""
    ensure_reportlab()
    d = Drawing(box_width, box_height)
    # Background
    d.add(Rect(0, 0, box_width, box_height, fillColor=COLORS["light_bg"], strokeColor=COLORS["light_border"], strokeWidth=0.5))
    # Color accent bar at top
    d.add(Rect(0, box_height - 4, box_width, 4, fillColor=color, strokeColor=None))
    # Value — 18pt unless it would run past the edge of the box. Short values
    # ("34/100", "PASS") are unaffected; the descriptive assessment wording is
    # what needs the room.
    value_size = 18.0
    usable = box_width - 12
    while value_size > 7 and string_width(value, "Helvetica-Bold", value_size) > usable:
        value_size -= 0.5
    d.add(String(box_width / 2, box_height * 0.35, value, fontSize=value_size, fillColor=color, textAnchor="middle", fontName="Helvetica-Bold"))
    # Label
    d.add(String(box_width / 2, 8, label, fontSize=8, fillColor=COLORS["gray_text"], textAnchor="middle", fontName="Helvetica"))
    return d


