def _draw_footer(canvas_obj, doc, is_cover=False):
    """Draw the professional footer on every page."""
    ensure_reportlab()
    width, height = letter
    canvas_obj.saveState()

    # CONFIDENTIAL watermark on cover page
    if is_cover:
        canvas_obj.setFont("Helvetica-Bold", 60)
        canvas_obj.setFillAlpha(0.06)
        canvas_obj.setFillColor(COLORS["danger"])
        canvas_obj.saveState()
        canvas_obj.translate(width / 2, height / 2)
        canvas_obj.rotate(35)
        canvas_obj.drawCentredString(0, 0, "CONFIDENTIAL")
        canvas_obj.restoreState()
        canvas_obj.setFillAlpha(1.0)

    # Footer line separator
    footer_y = 0.55 * inch
    canvas_obj.setStrokeColor(COLORS["light_border"])
    canvas_obj.setLineWidth(0.5)
    canvas_obj.line(0.75 * inch, footer_y, width - 0.75 * inch, footer_y)

    # Left: branding
    canvas_obj.setFont("Helvetica", 7)
    canvas_obj.setFillColor(COLORS["gray_text"])
    canvas_obj.drawString(0.75 * inch, 0.38 * inch, "AI Fund Administration Assistant")

    # Center: CONFIDENTIAL
    canvas_obj.setFont("Helvetica-Bold", 7)
    canvas_obj.setFillColor(COLORS["danger"])
    canvas_obj.drawCentredString(width / 2, 0.38 * inch, "CONFIDENTIAL")

