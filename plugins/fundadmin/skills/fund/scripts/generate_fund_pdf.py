class _PageCounter:
    """Counts pages and replaces a placeholder in the final PDF with the total.

    Uses a unique ASCII placeholder that ReportLab will embed literally in the
    PDF content stream (text rendering ops are not compressed individually).
    After doc.build(), call finalize() to patch the PDF file in place.
    """
    # Fixed-width placeholder — easy to find/replace in raw PDF bytes.
    # Must be unique and unlikely to collide with real content.
    placeholder = "PGCNT"

    def __init__(self):
        self._count = 0

    def on_first_page(self, canvas_obj, doc):
        _draw_footer(canvas_obj, doc, is_cover=True)
        self._count += 1

    def on_later_pages(self, canvas_obj, doc):
        _draw_footer(canvas_obj, doc, is_cover=False)
        self._count += 1

    def finalize(self, output_path: str):
        """Replace the placeholder with the actual total page count."""
        path = Path(output_path)
        raw = path.read_bytes()
        total_str = str(self._count).ljust(len(self.placeholder))
        raw = raw.replace(self.placeholder.encode("latin-1"), total_str.encode("latin-1"))
        path.write_bytes(raw)


def _on_first_page(canvas_obj, doc):  # noqa: F841 — kept for external callers
    """Cover page callback."""
    _draw_footer(canvas_obj, doc, is_cover=True)


def _on_later_pages(canvas_obj, doc):  # noqa: F841 — kept for external callers
    """Content pages callback."""
    _draw_footer(canvas_obj, doc, is_cover=False)


