def fidelity_styles():
    """Embed ReportLab's bundled TrueType fonts for portable text extraction."""
    import reportlab
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    font_dir = Path(reportlab.__file__).parent / "fonts"
    for name, filename in (("ReportText", "Vera.ttf"), ("ReportBold", "VeraBd.ttf"),
                           ("ReportItalic", "VeraIt.ttf"), ("ReportBoldItalic", "VeraBI.ttf")):
        if name not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(TTFont(name, str(font_dir / filename)))
    from reportlab.lib.fonts import addMapping
    for family, plain in (("ReportText", "ReportText"), ("ReportBold", "ReportBold")):
        for bold, italic, face in ((0, 0, plain), (1, 0, "ReportBold"),
                                   (0, 1, "ReportItalic" if plain == "ReportText" else "ReportBoldItalic"),
                                   (1, 1, "ReportBoldItalic")):
            addMapping(family, bold, italic, face)
    body = ParagraphStyle("ReportBody", fontName="ReportText", fontSize=9,
                          leading=13, spaceAfter=5, splitLongWords=True)
    heading = ParagraphStyle("ReportHeading", parent=body, fontName="ReportBold",
                             fontSize=13, leading=17, spaceBefore=12,
                             textColor=COLORS["primary"], keepWithNext=False)
    return body, heading


# Symbols the embedded Vera fonts cannot draw but that carry meaning in reports.
# Mapped to text so severity survives; anything unmapped keeps a [U+XXXX] marker.
SYMBOL_MAP = {
    "\U0001F534": "HIGH", "\U0001F7E0": "ELEVATED", "\U0001F7E1": "MEDIUM",
    "\U0001F7E2": "LOW", "\u2B1C": "[ ]", "\u2610": "[ ]", "\u2611": "[x]",
    "\u2705": "[x]", "\u274C": "[no]", "\u26A0": "WARNING", "\u2192": "->",
    "\u2190": "<-", "\u2194": "<->", "\uFE0F": "",
}


def glyph_safe(value, style):
    from reportlab.pdfbase import pdfmetrics

    glyphs = pdfmetrics.getFont(style.fontName).face.charToGlyph
    text = str(value)
    for symbol, label in SYMBOL_MAP.items():
        text = text.replace(symbol, label)
    return "".join(char if ord(char) in glyphs or char in "\n\t" else
                   f"[U+{ord(char):04X}]" for char in text)


def literal_paragraph(value, style):
    return Paragraph(escape(glyph_safe(value, style)).replace("\n", "<br/>"), style)


def inline_markup(value, style):
    """Escape everything, then typeset a small, safe inline subset.

    Source HTML stays visible text: escaping runs first, and only the tags added
    here reach ReportLab. Links keep their URL visible for auditability.
    """
    text = escape(glyph_safe(value, style))
    spans = []

    def keep(match):
        spans.append(f'<font color="#334155">{match.group(1)}</font>')
        return f"\x00{len(spans) - 1}\x00"

    text = re.sub(r"`([^`]+)`", keep, text)
    text = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r"\1 (\2)", text)
    text = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<b>\1</b>", text)
    text = re.sub(r"(?<![\w*])\*(?=\S)([^*]+?)(?<=\S)\*(?![\w*])", r"<i>\1</i>", text)
    text = re.sub(r"\x00(\d+)\x00", lambda m: spans[int(m.group(1))], text)
    return text.replace("\n", "<br/>")


def inline_paragraph(value, style):
    return Paragraph(inline_markup(value, style), style)


def block_paragraph(line, body, heading_styles, quote, bullet):
    """One non-table source line: heading, quote, list item or paragraph."""
    match = re.match(r"^(#{1,6})\s+(.*)$", line)
    if match:
        level = min(len(match.group(1)), 3)
        return inline_paragraph(match.group(2), heading_styles[level])
    match = re.match(r"^\s*>\s?(.*)$", line)
    if match:
        return inline_paragraph(match.group(1), quote)
    match = re.match(r"^(\s*)[-*+]\s+(\[[ xX]\]\s+)?(.*)$", line)
    if match:
        box = match.group(2)
        marker = "[x]" if box and box.strip().lower() == "[x]" else "[ ]" if box else "\u2022"
        style = ParagraphStyle("ReportBulletN", parent=bullet,
                               leftIndent=bullet.leftIndent + 10 * (len(match.group(1)) // 2))
        return Paragraph(inline_markup(match.group(3), style), style, bulletText=marker)
    return inline_paragraph(line, body)


# CommonMark thematic break: three or more -, * or _ (optionally spaced), up to three leading spaces.
HORIZONTAL_RULE = re.compile(r"^ {0,3}([-*_])(?:[ \t]*\1){2,}[ \t]*$")


def labelled_records(headers, rows, body):
    """A table too wide for columns, as one record per row with each value labelled.

    Every column name is repeated as a label inside each record, so no header
    line is printed; a header-only table still lists its column names.
    """
    story = [Spacer(1, 4)]
    if not rows:
        rows = [[""] * len(headers)]
    for number, row in enumerate(rows):
        if number:
            story.append(HRFlowable(width="100%", thickness=.3, color=COLORS["light_border"],
                                    spaceBefore=2, spaceAfter=4))
        for label, value in zip(headers, row):
            label_markup = inline_markup(label, body)
            value_markup = inline_markup(value, body)
            story.append(Paragraph(f"<b>{label_markup}:</b> {value_markup}".rstrip(), body))
    story.append(Spacer(1, 8))
    return story


def markdown_story(markdown, body, heading):
    """Render source blocks in order.

    Headings, tables, lists, block quotes and a safe inline subset (bold, italic,
    code, links) are typeset; everything else, including source HTML, stays
    visible text so the PDF can be audited against the Markdown.
    """
    heading_styles = {
        1: ParagraphStyle("ReportH1", parent=heading, fontSize=16, leading=20, spaceBefore=14),
        2: heading,
        3: ParagraphStyle("ReportH3", parent=heading, fontSize=11, leading=15, spaceBefore=10),
    }
    quote = ParagraphStyle("ReportQuote", parent=body, leftIndent=12,
                           textColor=COLORS["gray_text"])
    bullet = ParagraphStyle("ReportBullet", parent=body, leftIndent=14, bulletIndent=4)
    story = []
    lines = markdown.splitlines()
    index = 0
    fence = None

    def cells(line):
        line = line.strip()
        if line.startswith("|"):
            line = line[1:]
        if line.endswith("|") and not line.endswith(r"\|"):
            line = line[:-1]
        return [cell.strip().replace(r"\|", "|") for cell in
                re.split(r"(?<!\\)\|", line)]

    while index < len(lines):
        line = lines[index]
        marker = re.match(r"^\s*(`{3,}|~{3,})", line)
        if marker:
            if fence is None:
                fence = marker.group(1)[0]
            elif marker.group(1)[0] == fence:
                fence = None
            story.append(literal_paragraph(line, body))
            index += 1
            continue
        if not fence and HORIZONTAL_RULE.match(line):
            # A thematic break is layout, not content: draw it instead of printing "---".
            story.append(HRFlowable(width="100%", thickness=.5, color=COLORS["light_border"],
                                    spaceBefore=4, spaceAfter=6))
            index += 1
            continue
        if not fence and index + 1 < len(lines) and "|" in line and "|" in lines[index + 1]:
            separators = cells(lines[index + 1])
            headers = cells(line)
            if len(headers) == len(separators) and all(
                    re.fullmatch(r":?-{3,}:?", cell) for cell in separators):
                rows = [headers]
                index += 2
                while index < len(lines) and "|" in lines[index] and lines[index].strip():
                    row = cells(lines[index])
                    if len(row) != len(headers):
                        break
                    rows.append(row)
                    index += 1
                if len(headers) > 5 or any(len(cell) > 1200 for row in rows for cell in row):
                    story.extend(labelled_records(headers, rows[1:], body))
                else:
                    table = Table([[inline_paragraph(cell, body) for cell in row] for row in rows],
                                  colWidths=[6.5 * inch / len(headers)] * len(headers),
                                  repeatRows=1, splitByRow=1, splitInRow=1)
                    table.setStyle(TableStyle([
                        ("BACKGROUND", (0, 0), (-1, 0), COLORS["light_border"]),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("GRID", (0, 0), (-1, -1), .3, COLORS["light_border"]),
                        ("LEFTPADDING", (0, 0), (-1, -1), 6),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                    ]))
                    story.extend([table, Spacer(1, 8)])
                continue
        if line.strip():
            story.append(literal_paragraph(line, body) if fence else
                         block_paragraph(line, body, heading_styles, quote, bullet))
        else:
            story.append(Spacer(1, 5))
        index += 1
    return story


def structured_story(source, body, heading):
    """Render all structured fields, including extensions unknown to this tool."""
    story = []
    score = source.get("score")
    if score is not None:
        story.append(literal_paragraph(
            f'{source.get("score_label", DEFAULT_SCORE_LABEL)}: '
            f'{score}/{source.get("score_scale", 100)}', heading))
    else:
        story.append(literal_paragraph("Score: Not supplied", body))

    def render(value, label):
        if isinstance(value, dict):
            story.append(literal_paragraph(label, heading))
            if not value:
                story.append(literal_paragraph("{}", body))
            for key, child in value.items():
                render(child, str(key).replace("_", " "))
        elif isinstance(value, list):
            story.append(literal_paragraph(label, heading))
            if not value:
                story.append(literal_paragraph("[]", body))
            for index, child in enumerate(value, 1):
                render(child, str(index))
        else:
            text = "null" if value is None else str(value)
            story.append(literal_paragraph(f"{label}: {text}", body))

    for key, value in source.items():
        if key not in ({"score", "score_label", "score_scale"} if score is not None else {"score"}):
            render(value, str(key).replace("_", " "))
    return story


@contextmanager
def private_pdf_output(output_path: Path):
    """Reserve a new file and retain its descriptor through render and cleanup.

    O_EXCL refuses existing files, including dangling symlinks. A directory
    descriptor anchors cleanup if the parent is renamed during rendering.
    """
    directory_fd = os.open(output_path.parent, os.O_RDONLY | os.O_DIRECTORY)
    fd = None
    identity = None
    try:
        try:
            fd = os.open(output_path.name, os.O_WRONLY | os.O_CREAT | os.O_EXCL,
                         0o600, dir_fd=directory_fd)
        except FileExistsError:
            raise ValueError("Output already exists; choose a unique path with --output. "
                             "Existing files and symlinks are never overwritten.") from None
        identity = os.fstat(fd)
        try:
            os.fchmod(fd, 0o600)
            # Keep fd alive until cleanup finishes, including failures on close.
            with os.fdopen(fd, "wb", closefd=False) as stream:
                yield stream
                stream.flush()
                os.fsync(fd)
                current = os.stat(output_path.name, dir_fd=directory_fd, follow_symlinks=False)
                if (current.st_dev, current.st_ino) != (identity.st_dev, identity.st_ino):
                    raise RuntimeError("Output path changed during rendering; choose a unique path "
                                       "in a trusted output directory.")
        except BaseException:
            try:
                current = os.stat(output_path.name, dir_fd=directory_fd, follow_symlinks=False)
                if (current.st_dev, current.st_ino) == (identity.st_dev, identity.st_ino):
                    os.unlink(output_path.name, dir_fd=directory_fd)
            except FileNotFoundError:
                pass
            except OSError:
                # Do not mask the render error or delete a different file.
                print("WARNING: Could not remove incomplete PDF output; inspect the selected output path.",
                      file=sys.stderr)
            raise
    finally:
        if fd is not None:
            os.close(fd)
        os.close(directory_fd)


def build_pdf(data: dict, output_path: Path) -> Path:
    ensure_reportlab()
    data = normalize_report_data(data)
    output_path = Path(output_path)
    try:
        with private_pdf_output(output_path) as stream:
            _render_pdf(data, stream)
    except OSError as exc:
        raise RuntimeError(f"Cannot write PDF output: {exc.strerror or 'I/O failure'}") from None
    return output_path


def _render_pdf(data: dict, output_stream) -> None:
    ensure_reportlab()
    data = normalize_report_data(data)
    body, heading = fidelity_styles()

    from reportlab.pdfgen.canvas import Canvas

    class NumberedCanvas(Canvas):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self._page_states = []

        def showPage(self):
            self._page_states.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            states = self._page_states
            for state in states:
                self.__dict__.update(state)
                self._total_pages = len(states)
                _draw_footer(self, None)
                super().showPage()
            super().save()

    doc = SimpleDocTemplate(
        output_stream,
        pagesize=letter,
        leftMargin=0.75 * inch,
        rightMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
        pageCompression=1,
    )

    story = [literal_paragraph("Fund Document Review Report", heading)]
    if data.markdown is not None:
        story.extend(markdown_story(data.markdown, body, heading))
    else:
        story.extend(structured_story(data.source, body, heading))
    story.append(literal_paragraph(
        "AI-generated report. Not financial, legal or tax advice. Qualified human review is required. "
        "Not investment advice. Source limitations and citations remain applicable. "
        "This PDF was rendered locally; the source documents were processed by the AI host and "
        "its model provider, so confirm their confidentiality terms permit that processing.", body))

    doc.build(story, canvasmaker=NumberedCanvas)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    input_path = Path(args.input_resolved)
    output_path = Path(args.output_resolved)

    try:
        if input_path.resolve() == output_path.resolve():
            raise ValueError("Input and output must be different; choose a unique path with --output.")
        data = read_input_data(input_path)
        result = build_pdf(data, output_path)
    except (OSError, ValueError, RuntimeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:  # pragma: no cover - defensive fallback
        print(f"ERROR: unexpected PDF generation failure: {exc}", file=sys.stderr)
        return 1

    print(f"PDF generated: {result}")
    return 0


